"""
ScopeForgeX Professional Report Generator
==========================================

Generates professional Markdown assessment reports.

v0.6.1

Features:
    - Executive summary
    - Scope details
    - Methodology
    - Workflow execution summary
    - Attack surface statistics
    - Vulnerability findings
    - Risk summary
    - Tool execution tracking
    - Artifact tracking
    - Remediation guidance

Compatible with:
    - dict based tool results
    - ExecutionResult list based tool results
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

from .models import ReportData


###############################################################################
# Report Generator
###############################################################################


class ReportGenerator:
    """
    Markdown report generator.
    """

    TITLE = "ScopeForgeX Assessment Report"


    def __init__(
        self,
        report: ReportData,
    ) -> None:

        self.report = report
        self.lines: list[str] = []


    ###########################################################################
    # Markdown Helpers
    ###########################################################################

    def _line(
        self,
        text: str = "",
    ) -> None:

        self.lines.append(
            f"{text}\n"
        )


    def _blank(
        self,
    ) -> None:

        self.lines.append(
            "\n"
        )


    def _heading(
        self,
        level: int,
        title: str,
    ) -> None:

        self._line(
            f"{'#' * level} {title}"
        )

        self._blank()



    def _bullet(
        self,
        label: str,
        value,
    ) -> None:

        self._line(
            f"- **{label}:** {value}"
        )



    def _table(
        self,
        headers: list[str],
        rows: list[list[str]],
    ) -> None:

        self._line(
            "| "
            + " | ".join(headers)
            + " |"
        )

        self._line(
            "|"
            +
            "|".join(
                "---"
                for _ in headers
            )
            +
            "|"
        )


        for row in rows:

            self._line(
                "| "
                +
                " | ".join(
                    str(item)
                    for item in row
                )
                +
                " |"
            )


        self._blank()



    ###########################################################################
    # Report Sections
    ###########################################################################

    def _render_title(
        self,
    ) -> None:

        self._heading(
            1,
            self.TITLE,
        )

        self._line(
            "_Generated by ScopeForgeX_"
        )

        self._line(
            datetime.now().strftime(
                "%Y-%m-%d %H:%M:%S"
            )
        )

        self._blank()



    def _render_executive_summary(
        self,
    ) -> None:

        self._heading(
            2,
            "Executive Summary",
        )

        self._bullet(
            "Target",
            f"`{self.report.target}`",
        )

        self._bullet(
            "Profile",
            f"`{self.report.profile}`",
        )

        self._bullet(
            "Target Type",
            f"`{self.report.target_type}`",
        )

        self._blank()



    def _render_scope(
        self,
    ) -> None:

        self._heading(
            2,
            "Assessment Scope",
        )

        self._bullet(
            "Target",
            self.report.target,
        )

        self._bullet(
            "Target Type",
            self.report.target_type,
        )

        self._blank()



    def _render_methodology(
        self,
    ) -> None:

        self._heading(
            2,
            "Methodology",
        )

        methods = [
            "Reconnaissance",
            "Technology Enumeration",
            "Vulnerability Assessment",
            "Manual Validation Preparation",
            "Reporting",
        ]

        for method in methods:

            self._line(
                f"- {method}"
            )

        self._blank()



    def _render_workflow(
        self,
    ) -> None:

        self._heading(
            2,
            "Workflow Execution",
        )

        rows = []

        for stage in getattr(
            self.report,
            "stages",
            [],
        ):

            rows.append(
                [
                    stage.name,
                    stage.status,
                ]
            )


        if rows:

            self._table(
                [
                    "Stage",
                    "Status",
                ],
                rows,
            )

        else:

            self._line(
                "_No workflow information available._"
            )

            self._blank()



    def _render_statistics(
        self,
    ) -> None:

        self._heading(
            2,
            "Attack Surface Summary",
        )

        stats = self.report.statistics


        metrics = [

            (
                "Subdomains discovered",
                stats.subdomains_found,
            ),

            (
                "Alive hosts",
                stats.alive_hosts,
            ),

            (
                "Validated hosts",
                stats.final_hosts,
            ),

            (
                "URLs discovered",
                stats.urls_discovered,
            ),

            (
                "Nuclei findings",
                stats.nuclei_findings,
            ),

            (
                "Files generated",
                stats.files_generated,
            ),

        ]


        for label, value in metrics:

            self._bullet(
                label,
                f"**{value}**",
            )


        self._blank()



    def _render_findings(
        self,
    ) -> None:

        self._heading(
            2,
            "Vulnerability Findings",
        )


        findings = getattr(
            self.report,
            "findings",
            [],
        )


        if not findings:

            self._line(
                "No automated vulnerabilities were identified."
            )

            self._blank()

            return



        rows = []


        for finding in findings:

            rows.append(
                [
                    getattr(
                        finding,
                        "finding_id",
                        "-",
                    ),

                    getattr(
                        finding,
                        "severity",
                        "-",
                    ),

                    getattr(
                        finding,
                        "title",
                        "-",
                    ),

                ]
            )


        self._table(
            [
                "ID",
                "Severity",
                "Title",
            ],
            rows,
        )



    def _render_risk_summary(
        self,
    ) -> None:

        summary = getattr(
            self.report,
            "severity_summary",
            None,
        )

        if not summary:

            return


        self._heading(
            2,
            "Risk Summary",
        )


        rows = [

            [
                "Critical",
                summary.critical,
            ],

            [
                "High",
                summary.high,
            ],

            [
                "Medium",
                summary.medium,
            ],

            [
                "Low",
                summary.low,
            ],

            [
                "Informational",
                summary.informational,
            ],

        ]


        self._table(
            [
                "Severity",
                "Count",
            ],
            rows,
        )



    ###########################################################################
    # Tool Execution
    ###########################################################################

    def _render_tools(
        self,
    ) -> None:
        """
        Render tool execution results.

        Supports:
            - dictionary format
            - ExecutionResult list format
        """

        tool_results = getattr(
            self.report,
            "tool_results",
            None,
        )


        if not tool_results:

            return


        self._heading(
            2,
            "Tool Execution",
        )


        rows = []


        if isinstance(
            tool_results,
            dict,
        ):

            for tool, status in tool_results.items():

                rows.append(
                    [
                        tool,
                        status,
                    ]
                )


        elif isinstance(
            tool_results,
            list,
        ):

            for result in tool_results:

                tool = getattr(
                    result,
                    "tool",
                    "unknown",
                )


                success = getattr(
                    result,
                    "success",
                    False,
                )


                rows.append(
                    [
                        tool,
                        (
                            "Completed"
                            if success
                            else "Failed"
                        ),
                    ]
                )


        if rows:

            self._table(
                [
                    "Tool",
                    "Status",
                ],
                rows,
            )



    ###########################################################################
    # Artifacts
    ###########################################################################

    def _render_artifacts(
        self,
    ) -> None:

        if not self.report.generated_files:

            return


        self._heading(
            2,
            "Generated Artifacts",
        )


        for artifact in self.report.generated_files:

            self._line(
                f"- `{artifact}`"
            )


        self._blank()



    ###########################################################################
    # Notes
    ###########################################################################

    def _render_notes(
        self,
    ) -> None:

        warnings = getattr(
            self.report,
            "warnings",
            [],
        )


        if not warnings:

            return


        self._heading(
            2,
            "Execution Notes",
        )


        for warning in warnings:

            self._line(
                f"- {warning}"
            )


        self._blank()



    ###########################################################################
    # Guidance
    ###########################################################################

    def _render_guidance(
        self,
    ) -> None:

        self._heading(
            2,
            "Analyst Guidance",
        )


        guidance = [

            "Review all automated findings before reporting them.",

            "Validate potential vulnerabilities manually.",

            "Investigate medium and high severity issues.",

            "Verify false positives before disclosure.",

            "Correlate results from multiple tools.",

        ]


        for item in guidance:

            self._line(
                f"- {item}"
            )


        self._blank()



    ###########################################################################
    # Public API
    ###########################################################################

    def generate_markdown(
        self,
        output_file: str,
    ) -> None:

        self.lines.clear()


        self._render_title()

        self._render_executive_summary()

        self._render_scope()

        self._render_methodology()

        self._render_workflow()

        self._render_statistics()

        self._render_findings()

        self._render_risk_summary()

        self._render_tools()

        self._render_artifacts()

        self._render_notes()

        self._render_guidance()


        Path(
            output_file,
        ).write_text(
            "".join(
                self.lines
            ),
            encoding="utf-8",
        )


###############################################################################
# Public API
###############################################################################

__all__ = [
    "ReportGenerator",
]
