"""
ScopeForgeX Sensitive Files Analyzer
=====================================

Native analyzer for identifying potentially sensitive files and resources
from previously collected HTTP/web evidence.

The analyzer does not perform network requests. It evaluates URLs, paths,
HTTP metadata, and response evidence supplied by ScopeForgeX collectors.

Responsibilities
----------------

- Identify potentially sensitive files and resources.
- Recognize common configuration, source-control, backup, debug, and
  source-map exposures.
- Identify directory-listing indicators.
- Preserve the original resource evidence.
- Produce normalized observations for the universal Finding pipeline.
- Avoid treating every unusual filename as a vulnerability.
- Keep detection independent from HTTP execution and command construction.

Architecture
------------

HTTP / Web Enumeration
        |
        v
Sensitive Files Analyzer
        |
        +--> Resource Observations
        |
        +--> Security Findings
                    |
                    v
             Finding Normalizer
                    |
                    v
             Correlation Engine
                    |
                    v
                  Report

Design Principles
-----------------

- Analyzer only; no network execution.
- Discovery of a potentially sensitive path is not automatically proof
  that sensitive contents are exposed.
- Confidence reflects the evidence supplied to the analyzer.
- Exact response status and content indicators are preserved when present.
- Secrets are not extracted or displayed by this analyzer.
- Directory listing detection is based on explicit evidence rather than
  assumptions from a directory-looking URL.
- The universal Finding model remains the canonical downstream structure.

v1.0.0
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Iterable, Mapping
from urllib.parse import urlsplit


